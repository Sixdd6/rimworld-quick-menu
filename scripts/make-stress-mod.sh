#!/usr/bin/env bash
# Generate the TEST-ONLY stress mod (sixdd.QuickMenuStress) used for P-11c / W-1 / W-2 in-game measurements.
# Usage: scripts/make-stress-mod.sh [N=2000] [OUT_DIR=dist/stress/QuickMenuStress]   (N: 1..50000; use 2000 and 8000)
# Output is outside mod/ and gitignored (dist/). scripts/package.sh zips only git-tracked mod/ files, so it never ships.
# Uses only vanilla textures by path. Streams through awk, so memory stays flat for any N.
set -euo pipefail
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
repo="$(cd "$here/.." && pwd)"
n="${1:-2000}"
out="${2:-$repo/dist/stress/QuickMenuStress}"
case "$n" in ''|*[!0-9]*) echo "N must be a positive integer, got '$n'" >&2; exit 1 ;; esac
[ "$n" -ge 1 ] && [ "$n" -le 50000 ] || { echo "N must be 1..50000" >&2; exit 1; }
case "$out" in */QuickMenuStress) ;; *) echo "OUT_DIR must end in /QuickMenuStress (safety: it is deleted and recreated)" >&2; exit 1 ;; esac

case "$out" in "$repo/mod"|"$repo/mod/"*) echo "OUT_DIR must not be under the repo's mod/ folder" >&2; exit 1 ;; esac
if [ -e "$out" ]; then
  grep -qs 'sixdd\.QuickMenuStress' "$out/About/About.xml" || { echo "$out exists and is not a Quick Menu stress mod (no sixdd.QuickMenuStress in About/About.xml); refusing to delete it" >&2; exit 1; }
fi
rm -rf "$out"
mkdir -p "$out/About" "$out/Defs"

cat > "$out/About/About.xml" <<'XML'
<?xml version="1.0" encoding="utf-8"?>
<ModMetaData>
  <name>Quick Menu STRESS (TEST ONLY)</name>
  <author>Sixdd</author>
  <packageId>sixdd.QuickMenuStress</packageId>
  <supportedVersions>
    <li>1.7</li>
  </supportedVersions>
  <description>TEST ONLY. Generated by scripts/make-stress-mod.sh. Adds fake buildables to stress-test Quick Menu. Never enable in a real save. Never shipped.</description>
  <loadAfter>
    <li>Ludeon.RimWorld</li>
  </loadAfter>
</ModMetaData>
XML

cat > "$out/Defs/Categories.xml" <<'XML'
<?xml version="1.0" encoding="utf-8"?>
<Defs>
  <DesignationCategoryDef>
    <defName>StressCatA</defName>
    <label>stress A</label>
    <order>900</order>
  </DesignationCategoryDef>
  <DesignationCategoryDef>
    <defName>StressCatB</defName>
    <label>stress B</label>
    <order>901</order>
  </DesignationCategoryDef>
  <DesignationCategoryDef>
    <defName>StressCatC</defName>
    <label>stress C</label>
    <order>902</order>
  </DesignationCategoryDef>
</Defs>
XML

awk -v n="$n" -v things="$out/Defs/Things.xml" -v groups="$out/Defs/Groups.xml" '
BEGIN {
  nc = split("Structure Production Furniture Power Security Misc Temperature Joy StressCatA StressCatB StressCatC", cat, " ")
  nr = split("Smithing Electricity ComplexFurniture", rp, " ")
  print "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n<Defs>" > things
  print "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n<Defs>" > groups
  for (i = 0; i < n; i++) {
    c = i % nc; q = int(i / nc)
    printf "  <ThingDef ParentName=\"BuildingBase\">\n    <defName>Stress_%d</defName>\n    <label>stress build %d</label>\n", i, i > things
    printf "    <description>Test only fake buildable %d.</description>\n", i > things
    print "    <graphicData>\n      <texPath>Things/Building/Furniture/Stool</texPath>\n      <graphicClass>Graphic_Multi</graphicClass>\n    </graphicData>" > things
    print "    <altitudeLayer>Building</altitudeLayer>\n    <passability>PassThroughOnly</passability>\n    <fillPercent>0.2</fillPercent>" > things
    print "    <statBases>\n      <MaxHitPoints>50</MaxHitPoints>\n      <WorkToBuild>100</WorkToBuild>\n      <Flammability>0</Flammability>\n    </statBases>" > things
    if (i % 3 == 0) {
      print "    <stuffCategories>\n      <li>Metallic</li>\n      <li>Woody</li>\n      <li>Stony</li>\n    </stuffCategories>\n    <costStuffCount>10</costStuffCount>" > things
    } else {
      print "    <costList>\n      <WoodLog>5</WoodLog>\n    </costList>" > things
    }
    printf "    <designationCategory>%s</designationCategory>\n", cat[c + 1] > things
    if (q % 2 == 0) {
      g = "Stress_G" cat[c + 1] "_" int(q / 16)
      printf "    <designatorDropdown>%s</designatorDropdown>\n", g > things
      if (!(g in seen)) { seen[g] = 1; printf "  <DesignatorDropdownGroupDef>\n    <defName>%s</defName>\n    <label>stress group %s</label>\n  </DesignatorDropdownGroupDef>\n", g, g > groups }
    }
    if (i % 5 == 0) printf "    <researchPrerequisites>\n      <li>%s</li>\n    </researchPrerequisites>\n", rp[(int(i / 5) % nr) + 1] > things
    printf "    <uiOrder>%d</uiOrder>\n", 3000 + i > things
    print "  </ThingDef>" > things
  }
  print "</Defs>" > things
  print "</Defs>" > groups
}'

# Well-formedness check
if command -v xmllint >/dev/null 2>&1; then
  xmllint --noout "$out"/About/About.xml "$out"/Defs/*.xml
else
  python3 -I - "$out" <<'PY'
import sys, glob
import xml.etree.ElementTree as ET
root = sys.argv[1]
for f in glob.glob(root + "/About/*.xml") + glob.glob(root + "/Defs/*.xml"):
    ET.parse(f)
PY
fi
echo "generated $n stress defs: $out"
echo "Link it with scripts/link-stress-mod.sh"
